import re

RULES: dict[str, list[tuple[str, int]]] = {
    "academic_leave": [
        # Название документа/цель заявления — сильнее общих слов «студент» и «курс».
        (r"\bакадемическ\w*\s+отпуск\w*\b", 10),
        (r"\bакад\.?\s+отпуск\w*\b", 8),
        (r"причин\w*\s+отпуск", 4),
        (r"дат\w*\s+начал\w*\s+отпуск", 3),
        (r"дат\w*\s+окончан\w*\s+отпуск", 3),
        (r"заявлени", 1),
    ],
    "internship_certificate": [
        # «Практика» встречается в отчётах и справках, а не только в заголовке.
        # Формы слова исключают ложное совпадение с прилагательным «практический».
        (r"\bпрактик(?:а|и|е|у|ой|ою|ам|ами|ах)?\b", 8),
        (r"\bотч[её]т\w*\s+по\s+(?:производственн\w*\s+|учебн\w*\s+)?практик(?:а|и|е|у|ой|ою|ам|ами|ах)?\b", 4),
        # При слабом OCR слово «практика» может потеряться, но в отчёте
        # часто остаётся читаемый заголовок «отчёт по производственной...».
        (r"\bотч[её]т\w*\s+по\s+производственн\w*\b", 6),
        (r"\bсправк\w*\s+о\s+практик(?:а|и|е|у|ой|ою|ам|ами|ах)?\b", 4),
        (r"\bруководител\w*\s+практик\w*\b", 4),
        (r"\bсрок\w*\s+практик\w*\b", 3),
        (r"\bорганизаци\w*\b", 1),
        (r"оценк", 1),
    ],
    "study_certificate": [
        # Общая «справка» и упоминание вуза сами по себе не определяют тип.
        (r"\bсправк\w*\s+об\s+обучени\w*\b", 10),
        (r"\bсправк\w*\s+о\s+том,?\s+что\b.{0,80}\bобуча\w+", 7),
        (r"направлени\w*\s+подготовк", 4),
        (r"форм\w*\s+обучени", 3),
        (r"период\w*\s+обучени", 3),
        # Общие слова вроде «обучающийся», «курс» и «университет» не должны
        # перевешивать название документа другого типа.
        (r"\bзачислен\w*\b", 2),
    ],
}


def classify(text: str) -> tuple[str, float]:
    """Возвращает (тип, уверенность 0..1)."""
    low = re.sub(r"\s+", " ", text.casefold().replace("ё", "е")).strip()
    # Школьная справка — не вузовская «справка об обучении» (п. 3.1):
    # МБОУ/СОШ/ученик/класс без вузовских маркеров — это другой тип,
    # иначе «обучается + справка» ложно даёт study_certificate 1.0.
    if re.search(r"школа|мбоу|мбдоу|маоу|сош\b|ученик\b|\b\d{1,2}[а-я]\s+класс", low) and not re.search(
        r"университет|институт|академия|колледж|вуз|направлени\w*\s+подготовк|зачислен", low
    ):
        return "неизвестно", 0.0
    scores: dict[str, int] = {}
    for doc_type, patterns in RULES.items():
        scores[doc_type] = sum(w for p, w in patterns if re.search(p, low))

    ranked = sorted(scores.items(), key=lambda item: item[1], reverse=True)
    best, best_score = ranked[0]
    second_score = ranked[1][1]
    # Не угадываем тип по словам вроде «справка», «курс» или «университет».
    # При близких оценках оставляем тип неопределённым — это безопаснее,
    # чем извлекать поля по схеме другого документа.
    if best_score < 3 or best_score - second_score < 2:
        return "неизвестно", 0.0

    total = sum(scores.values()) or 1
    return best, round(best_score / total, 3)
